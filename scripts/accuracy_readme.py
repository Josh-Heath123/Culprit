#!/usr/bin/env python3
"""Renders the README's accuracy section from the fault library's results.

Phase 34 part 2 (docs/DIAGNOSTIC_PLAN.md): "the README's number,
regenerated by a committed command from the fault library's results, with
its method and its count." The results are `cli/testdata/faultlib/
results.json`, which `just fault-library` writes when every case passes and
which CI's fault-library job must reproduce byte for byte. The number is
computed by the same function `GET /outcomes/accuracy` uses
(`app.verifications.service.tally`), so the README and the API cannot count
differently.

The section says, in so many words, that these are faults planted in
Culprit's own demo services — not accuracy on anyone's real system.

    uv run --project api python scripts/accuracy_readme.py          # rewrite README.md
    uv run --project api python scripts/accuracy_readme.py --check  # exit 1 if stale

Exit codes: 0 written or current · 1 stale (--check) · 2 could not run.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "cli" / "testdata" / "faultlib" / "results.json"
README = ROOT / "README.md"
BEGIN = "<!-- accuracy:begin -->"
END = "<!-- accuracy:end -->"

sys.path.insert(0, str(ROOT / "api"))
from app.verifications.service import fault_class, tally  # noqa: E402


def _share(verified: int, decided: int) -> str:
    return f"{100 * verified / decided:.0f}%" if decided else "none decided"


def render(results: dict[str, Any]) -> str:
    """The README section, from the results alone."""
    faults = results["faults"]
    report = tally(
        [
            {
                "complete": fault["complete"],
                "root_subject": fault["root_subject"],
                "verdict": fault["verdict"],
                "source": "planted",
            }
            for fault in faults
        ]
    )
    classes = report["classes"]
    verified = sum(row["verdicts"]["verified"] for row in classes)
    decided = sum(row["decided"] for row in classes)
    inconclusive = sum(row["inconclusive"] for row in classes)
    counted = [fault for fault in faults if fault["complete"]]
    partial = [fault for fault in faults if not fault["complete"]]

    lines = [
        BEGIN,
        "<!-- Rendered by `just accuracy-readme` from cli/testdata/faultlib/results.json."
        " Do not edit by hand: CI fails if this differs. -->",
        "",
        "## Accuracy, on faults we planted",
        "",
        f"**{verified} of {decided} planted faults verified fixed** "
        f"({_share(verified, decided)}), of {len(faults)} faults planted: "
        f"{report['outcomes']} outcomes, {inconclusive} inconclusive beside that, and "
        f"{report['partial_diagnoses_not_counted']} partial diagnoses not counted.",
        "",
        "**These are faults we planted, in Culprit's own three demo services, and "
        "nothing else. They are not accuracy on anyone's real system.** No outcome from a "
        "real system is counted here, because none has been recorded. A sample of "
        f"{report['outcomes']} planted faults says the loop works on the faults it was built "
        "against; it says nothing yet about the faults it was not.",
        "",
        "**Method.** Each fault in the library (`cli/testdata/faultlib/`) is planted in the "
        "demo stack, diagnosed by `culprit diagnose` from inside a service, its known fix is "
        "applied, and `culprit verify` measures every reading again, twice, and compares the "
        "environment with the record of it taken at diagnosis. An outcome is the verification "
        "of a **complete** diagnosis; its fault class is the subject kind of the diagnosis's "
        "root. Per class, `verified` is counted against the decided outcomes (every verdict "
        "but inconclusive), and inconclusive is reported beside it, never folded in. "
        "A `verified` outcome shows that the fix for the root the walk diagnosed was seen to "
        "fix what it saw failing; a fault diagnosed at the wrong root would be counted under "
        "that root's class, so this measures diagnosis-then-fix, not whether every diagnosis "
        "named the true cause. "
        "`GET /outcomes/accuracy` counts verifications recorded through the control plane "
        "the same way, with the same function, and says for each count whether its faults "
        "were planted or real.",
        "",
        "| Fault class | Planted fault | Outcomes | Verified | Decided | Inconclusive |",
        "|---|---|---|---|---|---|",
    ]
    for row in classes:
        names = ", ".join(
            f"`{fault['name']}`"
            for fault in counted
            if fault_class(fault["root_subject"]) == row["fault_class"]
        )
        lines.append(
            f"| `{row['fault_class']}` | {names} | {row['outcomes']} | "
            f"{row['verdicts']['verified']} | {row['decided']} | {row['inconclusive']} |"
        )
    lines.append("")
    if partial:
        lines.append(
            "Not counted, because the walk's diagnosis was partial — an outcome is the "
            "verification of a complete one: "
            + "; ".join(f"`{fault['name']}` ({fault['verdict']})" for fault in partial)
            + "."
        )
        lines.append("")
    scenarios = results.get("scenarios", [])
    if scenarios:
        lines.append(
            "Not counted either: the library's deliberate wrong and partial fixes, which check "
            "that verification says so rather than measure diagnosis — "
            + "; ".join(f"`{s['name']}` ({s['verdict']})" for s in scenarios)
            + "."
        )
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def replaced(readme: str, section: str) -> str:
    start, end = readme.find(BEGIN), readme.find(END)
    if start < 0 or end < start:
        raise ValueError(f"README.md has no {BEGIN} ... {END} section")
    return readme[:start] + section + readme[end + len(END) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if README.md is stale")
    args = parser.parse_args()
    try:
        results = json.loads(RESULTS.read_text(encoding="utf-8"))
        readme = README.read_text(encoding="utf-8")
        updated = replaced(readme, render(results))
    except (OSError, ValueError, KeyError) as exc:
        print(f"accuracy_readme: {exc}", file=sys.stderr)
        return 2
    if args.check:
        if updated != readme:
            print(
                "README.md's accuracy section is not what cli/testdata/faultlib/results.json "
                "renders: run `just accuracy-readme`",
                file=sys.stderr,
            )
            return 1
        print("README.md's accuracy section is current")
        return 0
    README.write_text(updated, encoding="utf-8", newline="\n")
    print("README.md's accuracy section rendered from", RESULTS.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
