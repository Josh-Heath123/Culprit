"""scripts/render_captures.py — the parts that decide what a README image
shows, tested without running anything. The captures themselves are
regenerated by `just readme-captures` against real runs."""

from __future__ import annotations

import sys
import xml.dom.minidom
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import render_captures as rc  # noqa: E402


def test_elide_keeps_the_first_entries_of_a_section_and_marks_the_rest() -> None:
    lines = ["Not checked (5) — gaps", "  a", "  b", "  c", "  d", "  e", "after"]
    expected = ["Not checked (5) — gaps", "  a", "  b", "  …", "after"]
    assert rc.elide(lines, "Not checked", 2) == expected


def test_elide_leaves_a_short_section_alone() -> None:
    lines = ["Not checked (1) — gaps", "  a"]
    assert rc.elide(lines, "Not checked", 4) == lines


def test_clip_never_shortens_a_command_line() -> None:
    command = "$ culprit " + "x" * 300
    assert rc.clip(command) == command


def test_clip_marks_a_shortened_output_line() -> None:
    clipped = rc.clip("y" * 300)
    assert len(clipped) == rc.MAX_LINE
    assert clipped.endswith("…")


def test_the_svg_is_well_formed_and_escapes_markup_in_output() -> None:
    svg = rc.render_svg(["$ culprit check", "a <b> & 'c'", "[breaks_request_path] x"])
    doc = xml.dom.minidom.parseString(svg)  # raises on unescaped markup
    texts = [t.firstChild.data for t in doc.getElementsByTagName("text")]
    assert texts == ["$ culprit check", "a <b> & 'c'", "[breaks_request_path] x"]


def test_every_capture_is_written_from_a_command_line() -> None:
    """Each committed image starts with the command that produced it."""
    for name in ("check", "diff", "probe"):
        svg = (ROOT / "docs" / "captures" / f"{name}.svg").read_text(encoding="utf-8")
        first = xml.dom.minidom.parseString(svg).getElementsByTagName("text")[0].firstChild.data
        assert first.startswith("$ culprit "), name


def test_a_crashed_extractor_is_recognised_and_an_honest_gap_is_not() -> None:
    crashed = '  web  client_calls  extractor "node" exited 1: node:internal/modules/...'
    honest = "  api  client_calls  culprit-extract-python@0.1.0 does not extract client_calls"
    assert rc.CRASHED_EXTRACTOR.search(crashed)
    assert not rc.CRASHED_EXTRACTOR.search(honest)
