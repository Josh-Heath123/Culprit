// The per-item rule (Phase 39 part 1, docs/PERFORMANCE_PLAN.md: "How Phase
// 39 is run", decision 2). probe.db.statements_per_request brackets one GET
// of a list route with snapshots of pg_stat_statements, in an environment
// declared isolated, and counts the list's items from the same response. For
// each normalised statement it has its calls in the bracket. The rule:
//
//   - with at least two items counted, a statement is run per item when its
//     calls in the bracket are at least the item count;
//   - with fewer than two, the list's own statement cannot be told from a
//     per-item one, so the reading is inconclusive, saying so.
//
// It names statements; it is not a finding. N+1 is evidence beneath a
// route over its declared latency budget (decision 1), so the reading is
// pass whether or not a statement is named, and its reason names them.
//
// culprit_model/per_item.py holds the same rule, and
// shared/tests/per_item_conformance.json, generated by
// shared/tests/test_per_item.py, holds the two to one answer. A reading's
// verdict and its per_item list are re-judged from its own integers by
// Reading.Validate, in Python and at POST /readings.

// StatementsPerRequestProbeID is the probe whose readings the rule judges.
const StatementsPerRequestProbeID = "probe.db.statements_per_request"

// MinPerItemItems is the fewest items the rule can judge.
const MinPerItemItems = 2

// maxPerItemCount is a reading's ceiling on any count, as everywhere.
const maxPerItemCount = math.MaxInt32

// PerItemStatement is one statement of the bracket as the rule reads it.
type PerItemStatement struct {
	QueryID string
	Calls   int
}

// ParsePerItem reads a statements_per_request reading's measurement: the
// item count and the bracket's statements.
func ParsePerItem(measured map[string]any) (int, []PerItemStatement, error) {
	items, err := boundedNumber(measured["items"], "items", 0, maxPerItemCount)
	if err != nil {
		return 0, nil, err
	}
	raw, ok := measured["statements"].([]any)
	if !ok {
		if typed, isTyped := measured["statements"].([]map[string]any); isTyped {
			for _, item := range typed {
				raw = append(raw, item)
			}
		} else {
			return 0, nil, shapeError("statements must be a list")
		}
	}
	if len(raw) > StatementReadingMax {
		return 0, nil, shapeError("a reading keeps at most %d statements", StatementReadingMax)
	}
	seen := map[string]bool{}
	out := make([]PerItemStatement, 0, len(raw))
	for index, item := range raw {
		statement, ok := item.(map[string]any)
		if !ok {
			return 0, nil, shapeError("statements[%d] must be an object", index)
		}
		queryID, ok := statement["queryid"].(string)
		if !ok || queryID == "" {
			return 0, nil, shapeError("statements[%d].queryid must be text", index)
		}
		if seen[queryID] {
			return 0, nil, shapeError("statements[%d].queryid %s appears twice", index, queryID)
		}
		seen[queryID] = true
		calls, err := boundedNumber(statement["calls"], fmt.Sprintf("statements[%d].calls", index), 1, maxPerItemCount)
		if err != nil {
			return 0, nil, err
		}
		out = append(out, PerItemStatement{QueryID: queryID, Calls: calls})
	}
	return items, out, nil
}

// PerItemOrder sorts statements as a reading keeps them: by calls, most
// first, then by queryid. Every statement the rule names therefore comes
// before every one it does not, so a capped reading keeps them first.
func PerItemOrder(statements []PerItemStatement) {
	sort.SliceStable(statements, func(i, j int) bool {
		if statements[i].Calls != statements[j].Calls {
			return statements[i].Calls > statements[j].Calls
		}
		return statements[i].QueryID < statements[j].QueryID
	})
}

// JudgePerItem is the rule: the verdict, the reason, and the queryids of the
// statements run per item, in PerItemOrder.
func JudgePerItem(measured map[string]any) (Verdict, string, []string, error) {
	items, statements, err := ParsePerItem(measured)
	if err != nil {
		return "", "", nil, err
	}
	if items < MinPerItemItems {
		return VerdictInconclusive, fmt.Sprintf(
			"the list held %d item(s); with fewer than %d, a statement run once per item cannot be "+
				"told from the list's own statement", items, MinPerItemItems), []string{}, nil
	}
	ordered := append([]PerItemStatement{}, statements...)
	PerItemOrder(ordered)
	perItem := []string{}
	var named []string
	for _, statement := range ordered {
		if statement.Calls >= items {
			perItem = append(perItem, statement.QueryID)
			named = append(named, fmt.Sprintf("%s (%d calls)", statement.QueryID, statement.Calls))
		}
	}
	if len(perItem) == 0 {
		if len(ordered) == 0 {
			return VerdictPass, fmt.Sprintf(
					"no statement ran once per item: no statement was called for the %d items", items),
				perItem, nil
		}
		return VerdictPass, fmt.Sprintf(
			"no statement ran once per item: the most called ran %d time(s) for %d items",
			ordered[0].Calls, items), perItem, nil
	}
	return VerdictPass, fmt.Sprintf("%d statement(s) ran at least once per item of %d: %s",
		len(perItem), items, strings.Join(named, ", ")), perItem, nil
}

// validatePerItem is Reading.Validate's per-item rule: a
// probe.db.statements_per_request reading's verdict, and the statements it
// names, must be the ones its own integers give.
func (r Reading) validatePerItem() error {
	if r.ProbeID != StatementsPerRequestProbeID || r.Verdict == VerdictRefused {
		return nil
	}
	if _, measured := r.Measured["statements"]; !measured {
		if r.Verdict != VerdictInconclusive {
			return fmt.Errorf("a %s per-item reading must carry the statements it was judged on", r.Verdict)
		}
		if _, named := r.Measured["per_item"]; named {
			return fmt.Errorf("a per-item reading names statements it does not carry")
		}
		return nil
	}
	verdict, _, perItem, err := JudgePerItem(r.Measured)
	if err != nil {
		return fmt.Errorf("a per-item reading's measurement is not the rule's input: %w", err)
	}
	if verdict != r.Verdict {
		return fmt.Errorf("a per-item reading says %s, but its own integers give %s", r.Verdict, verdict)
	}
	claimed, err := textList(r.Measured["per_item"])
	if err != nil {
		return fmt.Errorf("a per-item reading's per_item: %w", err)
	}
	if strings.Join(claimed, "\x00") != strings.Join(perItem, "\x00") || len(claimed) != len(perItem) {
		return fmt.Errorf("a per-item reading names %v, but its own integers give %v", claimed, perItem)
	}
	return nil
}

// textList reads a list of text, from Go or from JSON.
func textList(value any) ([]string, error) {
	switch list := value.(type) {
	case []string:
		return list, nil
	case []any:
		out := make([]string, 0, len(list))
		for _, item := range list {
			text, ok := item.(string)
			if !ok {
				return nil, shapeError("must be a list of text")
			}
			out = append(out, text)
		}
		return out, nil
	}
	return nil, shapeError("must be a list of text")
}
