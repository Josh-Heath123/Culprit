package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	"github.com/josh-heath123/culprit/cli/internal/probe"
)

// mirrorPath is the API's copy of the probe catalogue, which `GET /probes`
// serves. The API is Python and cannot link the Go catalogue, so it reads
// this file instead.
var mirrorPath = filepath.Join("..", "..", "..", "api", "app", "readings", "catalogue.json")

// TestTheAPICatalogueIsGeneratedFromTheBinary compares the whole mirror,
// byte for byte, with what `culprit probe --list --format json` prints.
//
// Phase 31.1 kept the mirror by hand and checked three fields of it (id,
// effect, timeout); every version, predicate and input change that phase
// made matched only because someone diffed it by eye. Phase 32 selects
// probes by their manifests, so a mirror that drifts in any field would
// show the dashboard a catalogue the walk does not use. The file is now
// written by `just probe-catalogue`, and this test fails on any difference
// at all — like check_schema_drift.py, not like a spot check.
func TestTheAPICatalogueIsGeneratedFromTheBinary(t *testing.T) {
	var generated bytes.Buffer
	if err := renderCatalogue(&generated, "json", probe.BuiltIn()); err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(mirrorPath)
	if err != nil {
		t.Fatalf("reading %s: %v", mirrorPath, err)
	}
	// A Windows checkout may have rewritten LF as CRLF; that is not drift.
	normalised := strings.ReplaceAll(string(committed), "\r\n", "\n")
	if normalised != generated.String() {
		t.Fatalf("api/app/readings/catalogue.json is not what the binary's catalogue "+
			"renders. Regenerate it with `just probe-catalogue` and read the diff — "+
			"it is the API's view of every probe.\n\n%s",
			firstDifference(normalised, generated.String()))
	}
}

// firstDifference names the first line the two documents disagree on, so a
// failure says where to look instead of printing both files.
func firstDifference(committed, generated string) string {
	left, right := strings.Split(committed, "\n"), strings.Split(generated, "\n")
	for index := 0; index < len(left) || index < len(right); index++ {
		var a, b string
		if index < len(left) {
			a = left[index]
		}
		if index < len(right) {
			b = right[index]
		}
		if a != b {
			return "first difference at line " + strconv.Itoa(index+1) +
				":\n  committed: " + a + "\n  generated: " + b
		}
	}
	return "the documents differ only in trailing content"
}
