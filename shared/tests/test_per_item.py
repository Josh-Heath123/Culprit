"""The per-item rule (Phase 39 part 1), held between Python and Go.

shared/tests/per_item_conformance.json is generated here. Its cases cross an
item count (none, one, the two the rule needs, a few, a page) with the
bracket's statements (none; the list's own statement alone; one run per
item, short of it, past it; the list's statement and a per-item one, as
an N+1 reads; two per item; ties; a full reading of twenty), and add the
shapes the rule refuses. Each records what culprit_model.per_item makes of
it, and cli/internal/model/per_item_test.go holds model.JudgePerItem to the
same record. The anchors below are asserted by hand, so the record is not
merely self-consistent.

After a deliberate change to the rule:

    cd api && uv run python ../shared/tests/test_per_item.py --write
"""

import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pytest
from culprit_model.latency import LatencyShapeError
from culprit_model.per_item import STATEMENTS_PER_REQUEST_PROBE_ID, judge_per_item
from culprit_model.readings import Reading
from culprit_model.subjects import build

FIXTURE = Path(__file__).parent / "per_item_conformance.json"

ITEM_COUNTS = [0, 1, 2, 3, 5, 50]


def _statements(items: int) -> dict[str, list[dict[str, Any]]]:
    """The bracket's statements, as a function of the item count."""
    n = max(items, 1)
    return {
        "none": [],
        "the list's own statement alone": [{"queryid": "101", "calls": 1}],
        "one statement, one call short of per item": [{"queryid": "202", "calls": max(n - 1, 1)}],
        "one statement, once per item": [{"queryid": "202", "calls": n}],
        "one statement, once per item and one more": [{"queryid": "202", "calls": n + 1}],
        "the list's statement and one per item (N+1)": [
            {"queryid": "101", "calls": 1},
            {"queryid": "202", "calls": n},
        ],
        "two per item, the second twice": [
            {"queryid": "101", "calls": 1},
            {"queryid": "202", "calls": n},
            {"queryid": "303", "calls": 2 * n},
        ],
        "a tie on calls, ordered by queryid": [
            {"queryid": "909", "calls": n},
            {"queryid": "808", "calls": n},
        ],
        "a negative queryid, as Postgres gives them": [
            {"queryid": "-4611686018427387904", "calls": n},
        ],
        "twenty statements, every one once": [
            {"queryid": str(1000 + index), "calls": 1} for index in range(20)
        ],
    }


SHAPE_CASES: list[tuple[str, dict[str, Any]]] = [
    ("no item count", {"statements": []}),
    ("a negative item count", {"items": -1, "statements": []}),
    ("a fractional item count", {"items": 1.5, "statements": []}),
    ("an item count that is true", {"items": True, "statements": []}),
    ("an item count past 2^31-1", {"items": 2**31, "statements": []}),
    ("an item count with no fraction, as Go's JSON gives it", {"items": 3.0, "statements": []}),
    ("statements not a list", {"items": 3, "statements": {"queryid": "1", "calls": 3}}),
    ("no statements", {"items": 3}),
    (
        "twenty-one statements",
        {"items": 3, "statements": [{"queryid": str(index), "calls": 1} for index in range(21)]},
    ),
    (
        "a queryid twice",
        {"items": 3, "statements": [{"queryid": "1", "calls": 3}, {"queryid": "1", "calls": 1}]},
    ),
    ("a statement of no calls", {"items": 3, "statements": [{"queryid": "1", "calls": 0}]}),
    ("an empty queryid", {"items": 3, "statements": [{"queryid": "", "calls": 3}]}),
    ("a queryid that is a number", {"items": 3, "statements": [{"queryid": 1, "calls": 3}]}),
    ("a statement that is not an object", {"items": 3, "statements": ["1"]}),
    (
        "a statement's text is not the rule's",
        {"items": 3, "statements": [{"queryid": "1", "calls": 3, "text": "SELECT $1"}]},
    ),
]


def _record(measured: dict[str, Any]) -> dict[str, Any]:
    try:
        verdict, reason, per_item = judge_per_item(measured)
    except LatencyShapeError:
        return {"error": True}
    return {"verdict": verdict, "reason": reason, "per_item": per_item}


def generate() -> list[dict[str, Any]]:
    cases = []
    for items in ITEM_COUNTS:
        for name, statements in _statements(items).items():
            measured = {"items": items, "statements": statements}
            cases.append(
                {
                    "name": f"{items} items, {name}",
                    "measured": measured,
                    "expect": _record(measured),
                }
            )
    for name, measured in SHAPE_CASES:
        cases.append({"name": name, "measured": measured, "expect": _record(measured)})
    return cases


def fixture() -> dict[str, Any]:
    return {
        "why": [
            "Phase 39 part 1. Generated by shared/tests/test_per_item.py --write. What "
            "culprit_model.per_item.judge_per_item and model.JudgePerItem make of a "
            "probe.db.statements_per_request reading's items and statements: the verdict, the "
            "reason and the queryids run per item, most calls first; error when the reading is "
            "not the rule's input."
        ],
        "cases": generate(),
    }


def _recorded() -> dict[str, Any]:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _expect(name: str) -> dict[str, Any]:
    return {case["name"]: case["expect"] for case in _recorded()["cases"]}[name]


def test_the_fixture_is_what_the_rule_makes_of_it() -> None:
    assert _recorded() == json.loads(json.dumps(fixture())), (
        "per_item_conformance.json is stale: "
        "cd api && uv run python ../shared/tests/test_per_item.py --write"
    )


@pytest.mark.parametrize(
    ("name", "verdict", "per_item"),
    [
        # The brief's cases: one statement per item is named; the items
        # loaded together name none; fewer than two items cannot tell.
        ("5 items, the list's statement and one per item (N+1)", "pass", ["202"]),
        ("50 items, the list's statement and one per item (N+1)", "pass", ["202"]),
        ("5 items, the list's own statement alone", "pass", []),
        ("50 items, none", "pass", []),
        ("1 items, the list's statement and one per item (N+1)", "inconclusive", []),
        ("0 items, one statement, once per item", "inconclusive", []),
        # The boundary: at the item count is per item, one short is not.
        ("2 items, one statement, once per item", "pass", ["202"]),
        ("5 items, one statement, one call short of per item", "pass", []),
        ("5 items, one statement, once per item and one more", "pass", ["202"]),
        # Most calls first, then by queryid.
        ("3 items, two per item, the second twice", "pass", ["303", "202"]),
        ("3 items, a tie on calls, ordered by queryid", "pass", ["808", "909"]),
        # With two items, the list's own statement run once is not per item.
        ("2 items, the list's own statement alone", "pass", []),
        ("2 items, twenty statements, every one once", "pass", []),
    ],
)
def test_the_anchors(name: str, verdict: str, per_item: list[str]) -> None:
    expect = _expect(name)
    assert expect["verdict"] == verdict
    assert expect["per_item"] == per_item


def test_the_boundary_is_held_by_hand() -> None:
    """Calls equal to the item count are per item, one fewer is not:
    asserted against the rule itself, not only against the record."""
    at = {"items": 5, "statements": [{"queryid": "202", "calls": 5}]}
    short = {"items": 5, "statements": [{"queryid": "202", "calls": 4}]}
    assert judge_per_item(at)[2] == ["202"]
    assert judge_per_item(short)[2] == []


def test_the_reasons_say_what_they_found() -> None:
    assert _expect("5 items, the list's statement and one per item (N+1)")["reason"] == (
        "1 statement(s) ran at least once per item of 5: 202 (5 calls)"
    )
    assert "fewer than 2" in _expect("1 items, none")["reason"]
    assert _expect("5 items, the list's own statement alone")["reason"] == (
        "no statement ran once per item: the most called ran 1 time(s) for 5 items"
    )


def test_the_shapes_the_rule_refuses() -> None:
    refused = {name for name, _ in SHAPE_CASES if _expect(name) == {"error": True}}
    accepted = {name for name, _ in SHAPE_CASES} - refused
    assert accepted == {
        "an item count with no fraction, as Go's JSON gives it",
        "a statement's text is not the rule's",
    }


def _reading(verdict: str, measured: dict[str, Any]) -> dict[str, Any]:
    return {
        "probe_id": STATEMENTS_PER_REQUEST_PROBE_ID,
        "probe_version": 1,
        "target": build("http", component="inventory-service", method="GET", path="/products"),
        "environment": "isolated",
        "verdict": verdict,
        "reason": "judged",
        "measured": measured,
        "taken_at": datetime(2026, 11, 17, tzinfo=UTC),
        "agent_id": "test",
    }


N_PLUS_ONE = {
    "items": 5,
    "statements": [{"queryid": "202", "calls": 5}, {"queryid": "101", "calls": 1}],
    "per_item": ["202"],
}


def test_a_reading_is_its_own_integers() -> None:
    assert Reading(**_reading("pass", N_PLUS_ONE)).verdict.value == "pass"
    with pytest.raises(ValueError, match="its own integers give pass"):
        Reading(**_reading("inconclusive", N_PLUS_ONE))
    with pytest.raises(ValueError, match="names"):
        Reading(**_reading("pass", {**N_PLUS_ONE, "per_item": []}))
    with pytest.raises(ValueError, match="names"):
        Reading(**_reading("pass", {**N_PLUS_ONE, "per_item": ["101", "202"]}))
    with pytest.raises(ValueError, match="list of text"):
        Reading(**_reading("pass", {k: v for k, v in N_PLUS_ONE.items() if k != "per_item"}))
    # Nothing bracketed: only "could not tell", and nothing named.
    with pytest.raises(ValueError, match="must carry the statements"):
        Reading(**_reading("pass", {"url": "http://x/products"}))
    with pytest.raises(ValueError, match="does not carry"):
        Reading(**_reading("inconclusive", {"per_item": ["202"]}))
    assert Reading(**_reading("inconclusive", {"quiet_calls": 3})).verdict.value == "inconclusive"


if __name__ == "__main__" and "--write" in sys.argv:
    FIXTURE.write_text(json.dumps(fixture(), indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(fixture()['cases'])} per-item cases")
