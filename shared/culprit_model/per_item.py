"""The per-item rule — Phase 39 part 1.

`probe.db.statements_per_request` brackets one GET of a list route with
snapshots of `pg_stat_statements`, in an environment declared isolated, and
counts the list's items from the same response. For each normalised
statement it has its calls in the bracket. The rule:

- with at least two items counted, a statement is run per item when its
  calls in the bracket are at least the item count;
- with fewer than two, the list's own statement cannot be told from a
  per-item one, so the reading is **inconclusive**, saying so.

It names statements; it is not a finding. N+1 is evidence beneath a route
over its declared latency budget, so the reading is **pass** whether or not
a statement is named, and its reason names them.

The Go half is `cli/internal/model/per_item.go`; both are held to
`shared/tests/per_item_conformance.json`, generated by
`shared/tests/test_per_item.py`. `Reading` refuses a per-item reading whose
verdict, or whose `per_item` list, its own integers do not give.

Deterministic and dependency-free (`.claude/rules/determinism.md`).
"""

from typing import Any

from culprit_model.latency import LatencyShapeError
from culprit_model.statements import STATEMENT_READING_MAX

STATEMENTS_PER_REQUEST_PROBE_ID = "probe.db.statements_per_request"
#: The fewest items the rule can judge.
MIN_PER_ITEM_ITEMS = 2
_MAX_COUNT = 2**31 - 1


def _bounded(value: Any, name: str, minimum: int, maximum: int) -> int:
    # The same rule as culprit_model.statements: bool is not a count, and a
    # float with no fraction is (JSON decoded in Go arrives as one).
    if isinstance(value, bool):
        raise LatencyShapeError(f"{name} must be a whole number")
    if isinstance(value, float):
        if not value.is_integer():
            raise LatencyShapeError(f"{name} must be a whole number")
        value = int(value)
    if not isinstance(value, int) or value < minimum:
        raise LatencyShapeError(f"{name} must be a whole number of at least {minimum}")
    if value > maximum:
        raise LatencyShapeError(f"{name} must be at most {maximum}")
    return value


def per_item_inputs(measured: dict[str, Any]) -> tuple[int, list[tuple[str, int]]]:
    """The item count and the bracket's (queryid, calls) pairs."""
    items = _bounded(measured.get("items"), "items", 0, _MAX_COUNT)
    raw = measured.get("statements")
    if not isinstance(raw, list):
        raise LatencyShapeError("statements must be a list")
    if len(raw) > STATEMENT_READING_MAX:
        raise LatencyShapeError(f"a reading keeps at most {STATEMENT_READING_MAX} statements")
    seen: set[str] = set()
    out: list[tuple[str, int]] = []
    for index, statement in enumerate(raw):
        if not isinstance(statement, dict):
            raise LatencyShapeError(f"statements[{index}] must be an object")
        query_id = statement.get("queryid")
        if not isinstance(query_id, str) or not query_id:
            raise LatencyShapeError(f"statements[{index}].queryid must be text")
        if query_id in seen:
            raise LatencyShapeError(f"statements[{index}].queryid {query_id} appears twice")
        seen.add(query_id)
        calls = _bounded(statement.get("calls"), f"statements[{index}].calls", 1, _MAX_COUNT)
        out.append((query_id, calls))
    return items, out


def _order(statements: list[tuple[str, int]]) -> list[tuple[str, int]]:
    """Most calls first, then by queryid, as Go's PerItemOrder."""
    return sorted(statements, key=lambda pair: (-pair[1], pair[0]))


def judge_per_item(measured: dict[str, Any]) -> tuple[str, str, list[str]]:
    """The verdict, the reason, and the queryids run per item, in order."""
    items, statements = per_item_inputs(measured)
    if items < MIN_PER_ITEM_ITEMS:
        return (
            "inconclusive",
            f"the list held {items} item(s); with fewer than {MIN_PER_ITEM_ITEMS}, a statement run "
            "once per item cannot be told from the list's own statement",
            [],
        )
    ordered = _order(statements)
    per_item = [query_id for query_id, calls in ordered if calls >= items]
    if not per_item:
        if not ordered:
            return (
                "pass",
                f"no statement ran once per item: no statement was called for the {items} items",
                [],
            )
        return (
            "pass",
            f"no statement ran once per item: the most called ran {ordered[0][1]} time(s) "
            f"for {items} items",
            [],
        )
    named = ", ".join(
        f"{query_id} ({calls} calls)" for query_id, calls in ordered if calls >= items
    )
    return (
        "pass",
        f"{len(per_item)} statement(s) ran at least once per item of {items}: {named}",
        per_item,
    )
